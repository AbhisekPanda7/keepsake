package com.keepsake.storage;

import com.keepsake.common.ApiException;
import com.keepsake.config.KeepsakeProperties;
import java.util.Map;
import org.springframework.boot.autoconfigure.condition.ConditionalOnProperty;
import org.springframework.http.HttpHeaders;
import org.springframework.http.HttpStatus;
import org.springframework.http.MediaType;
import org.springframework.stereotype.Component;
import org.springframework.web.client.HttpClientErrorException;
import org.springframework.web.client.RestClient;

/**
 * Keeps images in a private Supabase Storage bucket, through its REST API. The service
 * key has full access to the project, so it stays on the server and never goes to a browser.
 */
@Component
@ConditionalOnProperty(name = "keepsake.storage.type", havingValue = "supabase")
public class SupabasePhotoStorage implements PhotoStorage {

    private final RestClient client;
    private final String bucket;

    public SupabasePhotoStorage(KeepsakeProperties properties, RestClient.Builder builder) {
        KeepsakeProperties.Storage config = properties.storage();
        if (config.supabaseUrl().isBlank() || config.supabaseKey().isBlank()) {
            throw new IllegalStateException("STORAGE_TYPE=supabase needs SUPABASE_URL and SUPABASE_SERVICE_KEY.");
        }
        this.bucket = config.supabaseBucket();
        String key = config.supabaseKey().trim();
        RestClient.Builder configured = builder
                .baseUrl(config.supabaseUrl().replaceAll("/+$", "") + "/storage/v1")
                .defaultHeader("apikey", key);
        // A legacy service_role key is a JWT and is also sent as the bearer token. A newer
        // secret key (sb_secret_...) isn't a JWT, and Storage refuses it as one.
        if (isLegacyJwt(key)) configured.defaultHeader(HttpHeaders.AUTHORIZATION, "Bearer " + key);
        this.client = configured.build();
    }

    static boolean isLegacyJwt(String key) {
        return key.startsWith("eyJ") && key.split("\\.", -1).length == 3;
    }

    @Override
    public void put(String key, byte[] bytes, String contentType) {
        client.post()
                .uri(objectPath(key))
                .contentType(MediaType.parseMediaType(contentType))
                .body(bytes)
                .retrieve()
                .toBodilessEntity();
    }

    @Override
    public byte[] get(String key) {
        try {
            return client.get().uri(objectPath(key)).retrieve().body(byte[].class);
        } catch (HttpClientErrorException.NotFound | HttpClientErrorException.BadRequest e) {
            // Supabase can report a missing object as either of these.
            throw ApiException.notFound("photograph");
        }
    }

    @Override
    public void copy(String fromKey, String toKey) {
        client.post()
                .uri("/object/copy")
                .contentType(MediaType.APPLICATION_JSON)
                .body(Map.of("bucketId", bucket, "sourceKey", fromKey, "destinationKey", toKey))
                .retrieve()
                .toBodilessEntity();
    }

    @Override
    public void delete(String key) {
        try {
            client.delete().uri(objectPath(key)).retrieve().toBodilessEntity();
        } catch (HttpClientErrorException e) {
            if (e.getStatusCode() != HttpStatus.NOT_FOUND) throw e;
        }
    }

    /** Keys are UUIDs and slashes, generated by the server, so they're safe in a path as they are. */
    private String objectPath(String key) {
        return "/object/" + bucket + "/" + key;
    }
}
